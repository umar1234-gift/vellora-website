/**
 * VELLORA — static prerender. Runs after the client and SSR builds.
 * For every route it renders the real React app to HTML, injects it plus
 * the page's <head> into the built index.html, and writes <route>.html.
 * Also writes sitemap.xml, 404.html and a Netlify _redirects file with one
 * explicit rewrite per route (unknown URLs get a real 404, not a 200).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { site } from "../src/config/site.js";
import { products } from "../src/data/products.js";
import { categories } from "../src/data/categories.js";
import { renderHeadHtml } from "../src/lib/seo.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dist = path.join(root, "dist");
const serverEntry = path.join(root, "dist-server", "entry-server.js");

const { render } = await import(pathToFileURL(serverEntry).href);

/* ---------------- route table ---------------- */

const staticRoutes = [
	{ path: "/", priority: "1.0" },
	{ path: "/collections", priority: "0.9" },
	...categories.map((c) => ({
		path: `/collections/${c.key}`,
		priority: "0.8",
	})),
	...products.map((p) => ({
		path: `/product/${p.slug}`,
		priority: "0.7",
		images: p.images,
	})),
	{ path: "/about", priority: "0.5" },
	{ path: "/experiences", priority: "0.5" },
	{ path: "/contact", priority: "0.5" },
	{ path: "/shipping", priority: "0.3" },
	{ path: "/refund", priority: "0.3" },
	{ path: "/terms", priority: "0.3" },
];

/* ---------------- template ---------------- */

const template = fs.readFileSync(path.join(dist, "index.html"), "utf8");

/* Remove head tags that <Seo> owns so they are never duplicated. */
const stripped = template
	.replace(/<title>[\s\S]*?<\/title>/i, "")
	.replace(/<meta\s+name="description"[\s\S]*?\/>/i, "")
	.replace(/<meta\s+name="robots"[\s\S]*?\/>/i, "")
	.replace(/<meta\s+property="og:[a-z_:]+"[\s\S]*?\/>/gi, "")
	.replace(/<meta\s+name="twitter:[a-z_]+"[\s\S]*?\/>/gi, "")
	.replace(/<link\s+rel="canonical"[\s\S]*?\/>/i, "");

if (!stripped.includes('<div id="root"></div>')) {
	throw new Error('prerender: template is missing <div id="root"></div>');
}

function buildPage(url, { fallback = false } = {}) {
	const { html, head } = render(url);
	if (!head) throw new Error(`prerender: no <Seo> rendered for ${url}`);

	const rootTag = fallback
		? '<div id="root" data-fallback>'
		: '<div id="root">';

	return stripped
		.replace("</head>", `    ${renderHeadHtml(head)}\n  </head>`)
		.replace('<div id="root"></div>', `${rootTag}${html}</div>`);
}

function fileFor(routePath) {
	return routePath === "/"
		? path.join(dist, "index.html")
		: path.join(dist, `${routePath.slice(1)}.html`);
}

/* ---------------- render every route ---------------- */

const redirects = [];

for (const route of staticRoutes) {
	const out = fileFor(route.path);
	fs.mkdirSync(path.dirname(out), { recursive: true });
	fs.writeFileSync(out, buildPage(route.path));
	if (route.path !== "/") {
		redirects.push(`${route.path}  /${route.path.slice(1)}.html  200`);
	}
}

fs.writeFileSync(
	path.join(dist, "404.html"),
	buildPage("/page-not-found", { fallback: true }),
);

fs.writeFileSync(
	path.join(dist, "_redirects"),
	[
		"# Generated by scripts/prerender.mjs — do not edit by hand.",
		...redirects,
		"/*  /404.html  404",
		"",
	].join("\n"),
);

/* ---------------- sitemap ---------------- */

const esc = (s) =>
	s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

const urlEntries = staticRoutes
	.map((r) => {
		const loc = r.path === "/" ? `${site.domain}/` : `${site.domain}${r.path}`;
		const images = (r.images || [])
			.map(
				(src) =>
					`    <image:image><image:loc>${esc(site.domain + src)}</image:loc></image:image>`,
			)
			.join("\n");
		return [
			"  <url>",
			`    <loc>${esc(loc)}</loc>`,
			`    <priority>${r.priority}</priority>`,
			images,
			"  </url>",
		]
			.filter(Boolean)
			.join("\n");
	})
	.join("\n");

fs.writeFileSync(
	path.join(dist, "sitemap.xml"),
	`<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">
${urlEntries}
</urlset>
`,
);

/* ---------------- housekeeping ---------------- */

/* Source photo archive: stays in the repo, but is not served publicly. */
fs.rmSync(path.join(dist, "images", "products.zip"), { force: true });
fs.rmSync(path.join(root, "dist-server"), { recursive: true, force: true });

console.log(
	`prerender: ${staticRoutes.length} routes + 404.html + sitemap.xml written to dist/`,
);